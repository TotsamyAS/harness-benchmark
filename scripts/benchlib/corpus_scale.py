def text_size(data):
    def strings(value):
        if isinstance(value, dict):
            return sum(strings(v) for v in value.values())
        if isinstance(value, list):
            return sum(strings(v) for v in value)
        return len(str(value)) if value is not None else 0
    return strings(data)


